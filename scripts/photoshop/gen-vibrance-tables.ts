/**
 * Builds src/adjustments/vibranceTables.ts from Photoshop's Vibrance probes (cases-photoprobes.jsx,
 * pp-vib-v<level>.psd on the 32-step RGB cube):
 *   node scripts/run-ts.mjs scripts/photoshop/gen-vibrance-tables.ts <probe folder>
 * Each level is Photoshop's output for every cube colour (planar R, G, B; stored as the change from
 * the input, mod 256), deflated together and base64-encoded.
 */
import fs from 'node:fs';
import { deflateSync } from 'fflate';
import { probeSamples } from './photoprobe-compare';

const LEVELS = [-100, -75, -50, -25, -10, 10, 25, 50, 75, 100];
const dir = process.argv[2] ?? (console.error('usage: gen-vibrance-tables.ts <probe folder>'), process.exit(1));
const N = 32 * 32 * 32;
const raw = new Uint8Array(LEVELS.length * N * 3);
LEVELS.forEach((v, li) => {
  const s = probeSamples(`${dir}/pp-vib-v${v}.psd`);
  for (let c = 0; c < 3; c++)
    for (let i = 0; i < N; i++) raw[(li * 3 + c) * N + i] = (Math.round(s[i].ps[c]) - s[i].input[c] + 256) & 255;
});
const packed = Buffer.from(deflateSync(raw, { level: 9 })).toString('base64');
const lines = packed.match(/.{1,120}/g)!.map((l) => `  '${l}',`).join('\n');
fs.writeFileSync('src/adjustments/vibranceTables.ts', `/**
 * Photoshop's Vibrance, measured (generated by scripts/photoshop/gen-vibrance-tables.ts; do not edit).
 * For each level, Photoshop 2025's output for the 32-step RGB cube (input k · 255 / 31 per channel,
 * red index fastest), planar R, G, B, stored as output − input mod 256; all levels deflated, base64.
 */
export const VIBRANCE_LEVELS = [${LEVELS.join(', ')}];
export const VIBRANCE_TABLES = [
${lines}
].join('');
`);
console.log(`levels ${LEVELS.length}, ${raw.length} bytes -> ${packed.length} base64 chars`);
