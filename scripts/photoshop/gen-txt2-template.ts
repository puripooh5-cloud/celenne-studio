/**
 * Writes src/psd/txt2Template.ts: the document-level part of a Txt2 block as Photoshop 2025 writes
 * it (style sheets, composer settings, the fonts those reference), with its text objects and frames
 * removed. Celenne adds an object and a frame per text layer when it saves a document that has no
 * Txt2 of its own.
 *   node scripts/run-ts.mjs scripts/photoshop/gen-txt2-template.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { parseContainer } from '../../src/psd/container';
import { readTxt2Lossless, writeTxt2Lossless, tget, type TNode } from '../../src/psd/txt2Write';

const src = path.resolve('tests/fixtures/photoshop/text/text-point-arial.psd');
const blk = parseContainer(new Uint8Array(fs.readFileSync(src))).globalBlocks.find((b) => b.key === 'Txt2');
if (!blk) throw new Error('no Txt2 in ' + src);
const block = readTxt2Lossless(blk.data);
const root: TNode = { k: 'dict', v: block };
const objects = tget(root, '1', '1'), frames = tget(root, '0', '8', '0');
if (objects?.k !== 'arr' || frames?.k !== 'arr') throw new Error('unexpected Txt2 layout');
objects.v = [];
frames.v = [];
const b64 = Buffer.from(writeTxt2Lossless(block)).toString('base64');
const lines = b64.match(/.{1,100}/g)!.map((l) => `  '${l}',`).join('\n');
fs.writeFileSync(path.resolve('src/psd/txt2Template.ts'), `/**
 * The document-level part of Photoshop's Txt2 block (style sheets, composer settings and the fonts
 * they reference), as Photoshop 2025 writes it, with no text objects or frames. Generated by
 * scripts/photoshop/gen-txt2-template.ts from tests/fixtures/photoshop/text/text-point-arial.psd.
 */
const B64 = [
${lines}
].join('');

let bytes: Uint8Array | null = null;
export function txt2Template(): Uint8Array {
  if (!bytes) {
    const s = atob(B64);
    bytes = new Uint8Array(s.length);
    for (let i = 0; i < s.length; i++) bytes[i] = s.charCodeAt(i);
  }
  return bytes.slice();
}
`);
console.log('template', b64.length, 'base64 chars');
