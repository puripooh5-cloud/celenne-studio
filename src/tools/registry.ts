/** Registers every tool implementation with the editor. */
import { editor } from '../app/editor';
import { HandTool, RotateViewTool, ZoomTool } from './navigationTools';
import { MoveTool } from './moveTool';
import { LassoTool, MagicWandTool, MarqueeTool, ObjectSelectTool, PolyLassoTool, QuickSelectTool } from './selectionTools';
import { MagicEraserTool, PaintTool, PatchTool, RedEyeTool } from './paintTools';
import { ColorSamplerTool, EyedropperTool, GradientTool, PaintBucketTool, RulerTool } from './fillSampleTools';
import { CropTool, PerspectiveCropTool } from './cropTools';
import { TypeTool } from './typeTool';
import { SliceTool } from './sliceTool';
import { PluginTool } from './pluginTool';
import { ShapeTool } from './shapeTools';
import { AnchorTool, FreeformPenTool, PathSelectTool, PenTool } from './penTools';

export function registerTools(): void {
  const r = editor.registerTool.bind(editor);
  r('move', () => new MoveTool());
  r('marqueeRect', () => new MarqueeTool('marqueeRect'));
  r('marqueeEllipse', () => new MarqueeTool('marqueeEllipse'));
  r('marqueeRow', () => new MarqueeTool('marqueeRow'));
  r('marqueeColumn', () => new MarqueeTool('marqueeColumn'));
  r('lasso', () => new LassoTool());
  r('polyLasso', () => new PolyLassoTool('polyLasso'));
  r('magneticLasso', () => new PolyLassoTool('magneticLasso'));
  r('objectSelect', () => new ObjectSelectTool());
  r('quickSelect', () => new QuickSelectTool());
  r('magicWand', () => new MagicWandTool());
  r('crop', () => new CropTool());
  r('perspectiveCrop', () => new PerspectiveCropTool());
  r('slice', () => new SliceTool());
  r('eyedropper', () => new EyedropperTool());
  r('colorSampler', () => new ColorSamplerTool());
  r('ruler', () => new RulerTool());
  r('spotHealing', () => new PaintTool('spotHealing', 'spotHealing'));
  r('remove', () => new PaintTool('remove', 'remove'));
  r('healing', () => new PaintTool('healing', 'healing'));
  r('patch', () => new PatchTool());
  r('redEye', () => new RedEyeTool());
  r('brush', () => new PaintTool('brush', 'brush'));
  r('pencil', () => new PaintTool('pencil', 'pencil'));
  r('colorReplace', () => new PaintTool('colorReplace', 'colorReplace'));
  r('mixerBrush', () => new PaintTool('mixerBrush', 'mixerBrush'));
  r('cloneStamp', () => new PaintTool('cloneStamp', 'cloneStamp'));
  r('patternStamp', () => new PaintTool('patternStamp', 'patternStamp'));
  r('eraser', () => new PaintTool('eraser', 'eraser'));
  r('bgEraser', () => new PaintTool('bgEraser', 'bgEraser'));
  r('magicEraser', () => new MagicEraserTool());
  r('gradient', () => new GradientTool());
  r('paintBucket', () => new PaintBucketTool());
  r('blur', () => new PaintTool('blur', 'blur'));
  r('sharpen', () => new PaintTool('sharpen', 'sharpen'));
  r('smudge', () => new PaintTool('smudge', 'smudge'));
  r('dodge', () => new PaintTool('dodge', 'dodge'));
  r('burn', () => new PaintTool('burn', 'burn'));
  r('sponge', () => new PaintTool('sponge', 'sponge'));
  r('pen', () => new PenTool());
  r('freeformPen', () => new FreeformPenTool());
  r('addAnchor', () => new AnchorTool('addAnchor'));
  r('deleteAnchor', () => new AnchorTool('deleteAnchor'));
  r('convertPoint', () => new AnchorTool('convertPoint'));
  r('pathSelect', () => new PathSelectTool('pathSelect'));
  r('directSelect', () => new PathSelectTool('directSelect'));
  r('type', () => new TypeTool());
  r('typeVertical', () => new TypeTool(true));
  r('rectangle', () => new ShapeTool('rectangle'));
  r('ellipse', () => new ShapeTool('ellipse'));
  r('polygon', () => new ShapeTool('polygon'));
  r('line', () => new ShapeTool('line'));
  r('customShape', () => new ShapeTool('customShape'));
  r('hand', () => new HandTool());
  r('rotateView', () => new RotateViewTool());
  r('zoom', () => new ZoomTool());
  r('pluginTool', () => new PluginTool());
}
